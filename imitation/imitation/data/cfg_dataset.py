import torch
import torch.utils.data
import numpy as np
from imitation.data.dataset import SequenceDataset


class CFGSequenceDataset(torch.utils.data.Dataset):
    """
    Dataset for Classifier-Free Guidance training.

    Combines positive (success) and negative (failure) demonstrations.
    Each sample includes a class label vector c of shape (action_horizon,):
        - Success demos: c = [1, 1, ..., 1]  (all timesteps labeled as success)
        - Failure demos:
            - If use_timestep_labels=True: c is loaded from per-timestep c_labels
              in the HDF5 (generated by label_timesteps.py). Each entry is 1.0
              (pre-failure) or 0.0 (post-failure).
            - If use_timestep_labels=False: c = [0, 0, ..., 0] for the entire demo.
    
    Args:
        data_paths: List of HDF5 paths. First num_pos are positive, rest negative.
        num_pos: Number of positive data paths (default: 1).
        use_timestep_labels: If True, read per-timestep labels from HDF5.
        action_horizon: Number of actions per chunk (length of label vector c).
    """
    def __init__(self, data_paths, num_pos=1, use_timestep_labels=False, action_horizon=1, **kwargs):
        super().__init__()
        
        positive_data_paths = data_paths[:num_pos]
        negative_data_paths = data_paths[num_pos:]
        
        self.use_timestep_labels = use_timestep_labels
        self.action_horizon = action_horizon
        
        # For negative data: add c_labels to dataset_keys so it gets loaded
        neg_kwargs = dict(kwargs)
        if use_timestep_labels:
            existing_keys = list(neg_kwargs.get('dataset_keys', ['actions']))
            if 'c_labels' not in existing_keys:
                existing_keys.append('c_labels')
            neg_kwargs['dataset_keys'] = existing_keys
            
        kwargs['action_horizon'] = action_horizon
        neg_kwargs['action_horizon'] = action_horizon
        
        self.pos_dataset = SequenceDataset(data_paths=positive_data_paths, **kwargs)
        self.neg_dataset = SequenceDataset(data_paths=negative_data_paths, **neg_kwargs)
        
        self.pos_len = len(self.pos_dataset)
        self.neg_len = len(self.neg_dataset)
        self.total_len = self.pos_len + self.neg_len

    def get_normalization_stats(self):
        """Normalize using only positive (success) data statistics."""
        return self.pos_dataset.get_normalization_stats()

    def __len__(self):
        return self.total_len

    def __getitem__(self, index):
        if index < self.pos_len:
            # Success demo: all actions labeled as success
            traj = self.pos_dataset[index]
            traj['c'] = np.ones(self.action_horizon, dtype=np.float32)
        else:
            # Failure demo
            traj = self.neg_dataset[index - self.pos_len]
            
            if self.use_timestep_labels:
                # Per-timestep labels: one label per action in the chunk
                traj['c'] = self._get_timestep_labels_for_action_chunk(index - self.pos_len)
            else:
                # Coarse labeling: entire demo is failure
                traj['c'] = np.zeros(self.action_horizon, dtype=np.float32)
        
        return traj

    def _get_timestep_labels_for_action_chunk(self, neg_index):
        """
        Look up per-timestep labels for the action chunk at neg_index.
        
        Returns c_labels for indices [index_in_demo, ..., index_in_demo + action_horizon - 1],
        clamped at episode boundaries. This aligns with how SequenceDataset reads
        actions for the chunk (batch['actions'][:, -1]).
        """
        if self.neg_dataset.split == 'val':
            actual_index = neg_index + self.neg_dataset.train_split
        else:
            actual_index = neg_index

        file_id = self.neg_dataset._index_to_file_id[actual_index]
        demo_id = self.neg_dataset._index_to_demo_id[file_id][actual_index]
        demo_start = self.neg_dataset._demo_id_to_start_indices[file_id][demo_id]
        index_in_demo = actual_index - demo_start

        c_labels = self.neg_dataset.get_dataset_for_ep(file_id, demo_id, "c_labels")
        c_arr = np.array(c_labels) if not isinstance(c_labels, np.ndarray) else c_labels

        demo_length = self.neg_dataset._demo_id_to_demo_length[file_id][demo_id]
        indices = np.arange(index_in_demo, index_in_demo + self.action_horizon)
        indices = np.minimum(indices, min(demo_length, len(c_arr)) - 1)
        return c_arr[indices].astype(np.float32)
