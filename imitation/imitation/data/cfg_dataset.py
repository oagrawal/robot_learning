import torch
import torch.utils.data
import numpy as np
from imitation.data.dataset import SequenceDataset


class CFGSequenceDataset(torch.utils.data.Dataset):
    def __init__(self, data_paths, num_pos=1, use_timestep_labels=False, action_horizon=1, **kwargs):
        """
        Dataset for CFG training with positive and negative demonstrations.
        
        Args:
            data_paths: List of HDF5 paths. First num_pos are positive, rest are negative.
            num_pos: Number of positive data paths.
            use_timestep_labels: If True, read per-timestep c_labels from the negative HDF5
                                 (generated by label_timesteps.py). If False, use coarse 
                                 trajectory-level labels (c=1.0 for positive, c=0.0 for negative).
            action_horizon: Number of actions predicted per step. Used to look ahead when
                            reading per-timestep labels to avoid boundary contamination.
        """
        super().__init__()
        
        positive_data_paths = data_paths[:num_pos]
        negative_data_paths = data_paths[num_pos:]
        
        self.use_timestep_labels = use_timestep_labels
        self.action_horizon = action_horizon
        
        # If using timestep labels, add c_labels to dataset_keys so it gets cached
        neg_kwargs = dict(kwargs)
        if use_timestep_labels:
            existing_keys = list(neg_kwargs.get('dataset_keys', ['actions']))
            if 'c_labels' not in existing_keys:
                existing_keys.append('c_labels')
            neg_kwargs['dataset_keys'] = existing_keys
        
        self.pos_dataset = SequenceDataset(data_paths=positive_data_paths, **kwargs)
        self.neg_dataset = SequenceDataset(data_paths=negative_data_paths, **neg_kwargs)
        
        self.pos_len = len(self.pos_dataset)
        self.neg_len = len(self.neg_dataset)
        self.total_len = self.pos_len + self.neg_len

    def get_normalization_stats(self):
        return self.pos_dataset.get_normalization_stats()

    def __len__(self):
        return self.total_len

    def __getitem__(self, index):
        if index < self.pos_len:
            # Positive demo — all timesteps are c=1.0
            traj = self.pos_dataset[index]
            traj['c'] = np.array([1.0], dtype=np.float32)
        else:
            # Negative demo
            traj = self.neg_dataset[index - self.pos_len]
            
            if self.use_timestep_labels:
                # Read per-timestep c_label for this specific timestep
                c_label = self._get_timestep_label(index - self.pos_len)
                traj['c'] = np.array([c_label], dtype=np.float32)
            else:
                # Coarse labeling: entire trajectory is c=0.0
                traj['c'] = np.array([0.0], dtype=np.float32)
        
        return traj

    def _get_timestep_label(self, neg_index):
        """
        Get the c_label for a specific timestep in the negative dataset.
        
        To avoid boundary contamination, we look ahead across the full
        action_horizon and return the MINIMUM c_label. This ensures that
        if ANY of the 8 target actions fall in the failure zone, the entire
        sample is labeled as failure (c=0.0).
        """
        # Resolve which file/demo/timestep this index maps to
        if self.neg_dataset.split == 'val':
            actual_index = neg_index + self.neg_dataset.train_split
        else:
            actual_index = neg_index
            
        file_id = self.neg_dataset._index_to_file_id[actual_index]
        demo_id = self.neg_dataset._index_to_demo_id[file_id][actual_index]
        demo_start = self.neg_dataset._demo_id_to_start_indices[file_id][demo_id]
        index_in_demo = actual_index - demo_start
        
        # Get c_labels from cache
        c_labels = self.neg_dataset.get_dataset_for_ep(file_id, demo_id, "c_labels")
        
        if isinstance(c_labels, np.ndarray):
            c_arr = c_labels
        else:
            c_arr = np.array(c_labels)
        
        # Look ahead across action_horizon: if ANY future action in the
        # predicted chunk crosses into failure, label the whole sample as failure
        end_idx = min(index_in_demo + self.action_horizon, len(c_arr))
        return float(np.min(c_arr[index_in_demo:end_idx]))
